"""The license gate (scripts/check_licenses.py): runtime dependencies of the backend
(from `uv export --no-dev`) and the frontend (package-lock.json, without dev-only
packages) must carry a license from the project's allowlist."""

import json
from email.message import Message
from pathlib import Path

import pytest

from scripts.check_licenses import (
    allowed,
    check_npm_lock,
    python_license,
    requirement_names,
)


@pytest.mark.parametrize(
    "expression",
    [
        "MIT",
        "mit",
        "BSD-3-Clause",
        "Apache-2.0",
        "MIT OR GPL-3.0-only",
        "(Apache-2.0 OR BSD-2-Clause)",
        "Apache-2.0 AND BSD-2-Clause",
        "MIT AND PSF-2.0",
        "Apache-2.0 WITH LLVM-exception",
        "MPL-2.0",
        "OFL-1.1",
        "BlueOak-1.0.0",
        "CC0-1.0",
        "0BSD",
        "MIT-0",
        "Unlicense",
        "Python-2.0",
        "PostgreSQL",
        "ISC",
    ],
)
def test_allowed_expressions(expression: str) -> None:
    assert allowed(expression)


@pytest.mark.parametrize(
    "expression",
    [
        "GPL-3.0-only",
        "AGPL-3.0-or-later",
        "LGPL-2.1",
        "MIT AND GPL-2.0",
        "(MIT AND (LGPL-3.0 OR GPL-2.0))",
        "BSD-4-Clause",
        "SSPL-1.0",
        "UNLICENSED",
        "SEE LICENSE IN LICENSE.md",
        "",
        "MIT OR",
        "(MIT",
    ],
)
def test_refused_or_unreadable_expressions(expression: str) -> None:
    assert not allowed(expression)


def _metadata(**fields: str | list[str]) -> Message:
    message = Message()
    for name, value in fields.items():
        for item in value if isinstance(value, list) else [value]:
            message[name.replace("_", "-")] = item
    return message


def test_python_license_prefers_the_expression_then_the_license_field_then_classifiers() -> None:
    both = _metadata(License_Expression="MIT", License="GPL-3.0")
    assert python_license(both) == "MIT"
    assert python_license(_metadata(License="BSD-3-Clause")) == "BSD-3-Clause"
    classifiers = ["License :: OSI Approved :: MIT License", "Programming Language :: Python"]
    assert python_license(_metadata(Classifier=classifiers)) == "MIT"


def test_python_license_understands_common_free_text() -> None:
    assert python_license(_metadata(License="3-Clause BSD License")) == "BSD-3-Clause"
    assert python_license(_metadata(License="MIT License")) == "MIT"
    # A whole license text in the field: fall back to the classifiers.
    text = _metadata(
        License="Copyright (c) 2020 Someone\n\nPermission is hereby granted ...",
        Classifier="License :: OSI Approved :: BSD License",
    )
    assert python_license(text) == "BSD-3-Clause"


def test_several_license_classifiers_mean_a_choice() -> None:
    dual = _metadata(
        Classifier=[
            "License :: OSI Approved :: Apache Software License",
            "License :: OSI Approved :: GNU General Public License v3 (GPLv3)",
        ]
    )
    assert python_license(dual) == "Apache-2.0 OR GPL-3.0-only"
    assert allowed(python_license(dual))


def test_python_license_is_empty_without_any_information() -> None:
    assert python_license(_metadata(Name="x")) == ""


def test_requirement_names_reads_uv_export() -> None:
    export = """# This file was autogenerated by uv
alembic==1.20.1
    # via to-herd-cats-ai
Mako==1.3.0
pycparser==3.12 ; implementation_name != 'PyPy'
pywin32==311 ; sys_platform == 'win32'
"""
    assert requirement_names(export) == ["alembic", "mako", "pycparser"]


def test_npm_lock_checks_runtime_packages_only(tmp_path: Path) -> None:
    lock = {
        "lockfileVersion": 3,
        "packages": {
            "": {"name": "frontend", "license": "Apache-2.0"},
            "node_modules/react": {"version": "19.0.0", "license": "MIT"},
            "node_modules/lib-gpl": {"version": "1.0.0", "license": "GPL-3.0-only"},
            "node_modules/no-license": {"version": "1.0.0"},
            "node_modules/old-style": {"version": "1.0.0", "license": {"type": "ISC"}},
            "node_modules/dev-gpl": {"version": "1.0.0", "license": "GPL-3.0", "dev": True},
        },
    }
    path = tmp_path / "package-lock.json"
    path.write_text(json.dumps(lock))
    checked, problems = check_npm_lock(path)
    assert checked == 4
    assert problems == [
        ("lib-gpl@1.0.0", "GPL-3.0-only"),
        ("no-license@1.0.0", ""),
    ]
